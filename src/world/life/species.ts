/**
 * The animals, modelled part by part: skins over spines, jointed legs with hooves or paws,
 * ears, eyes, horns, manes. Forward is +Z, the ground is y = 0. White fur takes the coat colour
 * of the individual; everything else keeps the colour written here.
 */

const make = (fn: (g: Rig) => void) => (detail: number): BufferGeometry => {
  const g = new Rig(detail);
  fn(g);
  return g.build();
};
const S = [-1, 1];
const LEGS = (hx: number, zf: number, zb: number): [number, number, number][] => [
  [1, -hx, zf],
  [2, hx, zf],
  [3, -hx, zb],
  [4, hx, zb],
];

/** How far the head must swing about `pivot` to bring the muzzle down to the grass. */
function reach(pivot: V3, muzzle: V3, k = 1, ground = 0.07): number {
  const dy = muzzle[1] - pivot[1];
  const dz = muzzle[2] - pivot[2];
  const R = Math.hypot(dy, dz);
  const phi = Math.atan2(dz, dy);
  const c = (ground - pivot[1]) / R;
  return (c <= -1 ? Math.PI - phi : Math.acos(Math.min(1, c)) - phi) * k;
}

/** A horn or antler beam through a row of points, ringed in two tones. */
function horn(g: Rig, pts: V3[], r0: number, r1: number, c: string, c2: string, kind: number = K.horn, tip?: string): void {
  g.loft(
    pts.map((p, i) => {
      const t = i / (pts.length - 1);
      const r = r0 + (r1 - r0) * t;
      return st(p[0], p[1], p[2], r, r, i === pts.length - 1 && tip ? tip : i % 2 ? c2 : c);
    }),
    { kind, seg: 8, sub: 2, cap: [0.3, 0.6], rnd: 0.4 },
  );
}

/** A lock of hair: fuller in the middle, rounded at the end. */
function lock(g: Rig, a: V3, b: V3, r: number, c: string, kind: number = K.fur, w?: number): void {
  g.loft([st(a[0], a[1], a[2], r * 0.7), st((a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2, r), st(b[0], b[1], b[2], r * 0.3)], { c, kind, seg: 6, sub: 2, cap: [0.4, 0.9], w: w === undefined ? undefined : [w, w] });
}

/** Three toes forward and one back (birds). */
function birdFoot(g: Rig, x: number, z: number, len: number, c: string): void {
  for (const a of [-0.5, 0, 0.5]) g.spike([x, len * 0.12, z], [x + Math.sin(a) * len, 0.004, z + Math.cos(a) * len], len * 0.11, c, K.beak);
  g.spike([x, len * 0.12, z], [x, 0.004, z - len * 0.6], len * 0.1, c, K.beak);
}

